import numpy as np
import matplotlib.pyplot as plt
from sklearn.cluster import KMeans

X = np.array([
    [2, 3],
    [3, 4],
    [4, 3],
    [8, 7],
    [9, 8],
    [8, 9],
    [1, 2],
    [10, 10],
    [9, 7],
    [3, 2]
])

print("Original Dataset:")
print(X)

plt.scatter(X[:, 0], X[:, 1], color='blue', marker='o')

plt.title("Original 2D Dataset")
plt.xlabel("X Coordinate")
plt.ylabel("Y Coordinate")

plt.grid(True)
plt.show()

kmeans = KMeans(n_clusters=2, random_state=42, n_init=10)


kmeans.fit(X)

labels = kmeans.labels_

centroids = kmeans.cluster_centers_

print("Cluster Labels:")
print(labels)

print("\nCluster Centroids:")
print(centroids)

print("Data Points and Their Clusters:\n")

for i in range(len(X)):
    print("Data Point:", X[i], "-> Cluster:", labels[i])

plt.figure(figsize=(8, 6))


plt.scatter(
    X[:, 0],
    X[:, 1],
    c=labels,
    cmap='viridis',
    s=100
)


plt.scatter(
    centroids[:, 0],
    centroids[:, 1],
    color='red',
    marker='X',
    s=250,
    label='Centroids'
)

plt.title("K-Means Clustering for 2D Data")
plt.xlabel("X Coordinate")
plt.ylabel("Y Coordinate")

plt.legend()
plt.grid(True)
plt.show()

print("Inertia:", kmeans.inertia_)

